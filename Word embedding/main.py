import os
import re
from gensim.models import Word2Vec

# Статический набор стоп-слов (предлоги, союзы, местоимения) для фильтрации шума.
# Позволяет очистить контекст без использования тяжелых внешних библиотек
STOP_WORDS = {
    'в', 'на', 'с', 'и', 'у', 'к', 'за', 'под', 'о', 'об', 'из', 'от', 'по', 'но', 'а',
    'да', 'что', 'как', 'это', 'я', 'он', 'она', 'они', 'мы', 'вы', 'ты', 'его', 'ее', 'их'
}

def main():
    dataset_name = "замок.test"
    model_name = "homograph_w2v.model"

    # Инициализируем пустой список, в котором сохраним предобработанный корпус текстов
    sentences = []

    # Открываем файл построчно, явно указывая кодировку UTF-8 для совместимости с Windows/Linux
    with open(dataset_name, 'r', encoding='utf-8') as f:
        for line in f:
            # Регулярное выражение [\w`]+ выделяет слова, включая в их состав символ обратного апострофа (`).
            # Это критически важно, так как стандартные токены разбивают "за`мок" на "за" и "мок", уничтожая омограф.
            words = re.findall(r'\b[\w`]+\b', line)

            processed_line = []
            for word in words:
                word_lower = word.lower()

                # Защита целевых токенов: омографы всегда добавляем в массив для обучения
                if word_lower in ['за`мок', 'замо`к']:
                    processed_line.append(word_lower)
                # Остальные слова фильтруем: исключаем союзы/предлоги из STOP_WORDS и чистые цифры
                elif word_lower not in STOP_WORDS and not word_lower.isdigit():
                    processed_line.append(word_lower)

            # Если после очистки в строке остались значимые слова, добавляем ее в общий массив
            if processed_line:
                sentences.append(processed_line)

    # Инициализация и сквозное обучение архитектуры Word2Vec.
    # Гиперпараметры оптимизированы под обучающую выборку небольшого объема:
    model = Word2Vec(
        sentences=sentences,  # Передаем подготовленный список списков слов
        vector_size=50,  # Размерность эмбеддингов снижена до 50 для защиты от переобучения (overfitting)
        window=3,  # Окно контекста (3 слова слева и справа) фиксирует локальные синтаксические связи
        min_count=1,  # Минимальная частота (1), чтобы не отбросить омографы при малом количестве вхождений
        epochs=30,  # Количество эпох (30) дает модели достаточно итераций для сходимости весов
        sg=1,  # Алгоритм Skip-gram (sg=1) выбран потому, что он качественнее находит контекст для редких слов
        workers=4  # Распределение вычислений на 4 потока процессора
    )

    # Сохраняем модель в бинарном формате. Рядом автоматически создадутся файлы матриц весов (.npy)
    model.save(model_name)

    # Блок внутренней валидации для оценки дистрибутивной семантики омографов
    print("\nПроверка обученных векторов:")
    targets = ['за`мок', 'замо`к']
    for target in targets:
        try:
            print(f"\nБлижайшие слова к омографу '{target}':")
            # Извлекаем топ-5 семантически ближайших токенов по косинусному расстоянию векторов
            for word, score in model.wv.most_similar(target, topn=5):
                print(f"  {word}: {score:.4f}")
        except KeyError:
            # Исключение отработает, если целевое слово отсутствовало в переданном файле датасета
            print(f"  Слово '{target}' не найдено.")


# Точка входа в скрипт, гарантирующая запуск кода только при прямом вызове файла
if __name__ == "__main__":
    main()

